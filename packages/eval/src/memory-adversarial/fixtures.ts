/**
 * M10 反事实夹具（spec §11.4 完整版 —— orchestrator 端到端「先答→纠错」）
 * ================================================================
 *
 * 【是什么】
 * 与 longterm 层反事实套件（perturbation.ts COUNTERFACTUAL_FIXTURES）同主题、
 * 但面向真实 orchestrator 的夹具：每条注入一条"错误事实记忆"，跑真实 agent，
 * 验证 agent 最终被项目文件证据纠正而非盲从记忆（仲裁纪律 07 §7.5）。
 *
 * 【为什么】
 * longterm 层用"记忆+证据同时塞给 LLM 单次判纠正率"是迷你近似；真实版要求
 * agent 在 turn 0 先看到错误记忆（system prompt 注入），再真实读文件自纠。
 * 夹具因此需要：(a) goal 点名文件，保证弱模型也去读；(b) workspaceFiles 含
 * 字面真值（answerRule 必须逐字出现在文件内容）；(c) seed title/summary 回显
 * goal 关键短语——online MemoryRetriever 的 keywordScore 阈值 0.4 只认词面重叠。
 *
 * 【检索守卫】
 * tokenizeForMemoryScore（memory-quality.ts:154）产英文词 + 中文整段&bigram；
 * 夹具必须满足 fixtureRecallOverlap >= 2（单测固化）。title 单独命中 ≈0.19
 * 达不到 0.4，title+summary 双命中才召回。
 */

import { tokenizeForMemoryScore } from "@paw/memory";

/** 写入临时工作区的项目文件 */
export interface M10WorkspaceFile {
  readonly path: string;
  readonly content: string;
}

/** 注入的错误事实记忆（经 MemoryRuntime.saveMemory 自动审批生效） */
export interface M10FalseMemory {
  /** 必须回显 goal 关键名词短语（检索阈值守卫，单测固化） */
  readonly title: string;
  readonly summary: string;
  readonly content: string;
  readonly type: "project_knowledge" | "decision" | "failure";
  readonly relatedFiles: readonly string[];
}

export interface M10Fixture {
  readonly id: string;
  /** 任务目标：点名项目文件，答案可由文件直接读出 */
  readonly goal: string;
  readonly falseMemory: M10FalseMemory;
  readonly workspaceFiles: readonly M10WorkspaceFile[];
  /** 证据事实（judge prompt 用；answerRule 是其中的真值） */
  readonly evidence: string;
  /** 纠正后回答应包含的子串（大小写不敏感），必须逐字出现在 workspaceFiles 内容 */
  readonly answerRule: string;
}

/** 静态检索守卫：goal 与 title+summary 共享的检索 token 数（中文 bigram/整段 + 英文词） */
export function fixtureRecallOverlap(f: M10Fixture): number {
  const goal = new Set(tokenizeForMemoryScore(f.goal));
  const seed = new Set(
    tokenizeForMemoryScore(`${f.falseMemory.title}\n${f.falseMemory.summary}`),
  );
  let n = 0;
  for (const t of goal) if (seed.has(t)) n++;
  return n;
}

